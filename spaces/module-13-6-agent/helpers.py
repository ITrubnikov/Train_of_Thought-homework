"""Подпорки для СЛАБОЙ модели — вынесены из app.py специально, отдельным файлом.

Это НЕ про скиллы (тема урока 13.6) и не про контракт tools (он живёт в
`cognopolis_tools.py`, одинаков для любой модели). Здесь — приёмы «как
докрутить агента, когда мозг слабоват», и их в этом шаблоне два:

1) `facts_seed` — затравка ФАКТОВ о живом мире: где житель стоит, что где
   лежит (деревья, камень, враги), где дом. Перечисляет все виды сразу, не
   выбирая ресурс по тексту, — иначе затравка смещала бы выбор скилла. Только
   факты — БЕЗ готового маршрута и без плана: процедуру теперь несёт skill (в
   этом весь урок 13.6), и отбирать у него работу затравкой было бы подменой
   темы.
2) `fact_check` — проверка результата состоянием, а не словами: сравнить склад
   до/после прогона и честно сказать, сдал агент ресурс или только заявил.

Маршрутная подсказка из 11.5 (`route_dirs`) ВОЗВРАЩЕНА как третья подпорка
(`route_hint`) — но иначе, чем в 11.5. Там она несла весь план (дойти →
gather → домой) и делала skill декоративным. Здесь порядок действий целиком
живёт в умении supply-run (реактивный цикл в его теле), а `route_hint` даёт
слабой локальной 7B только «куда шагать»: без этой подсказки qwen-7B на живой
карте путает координаты (рубит на соседней клетке) даже с хорошим умением —
проверено. Подсказка выключается переменной окружения `WEAK_MODEL_ROUTE=0`:
на модели посильнее навигацию целиком ведёт реактивный цикл умения, и тогда
видно, как процедуру несёт именно skill. На сильной модели весь этот файл
можно выкинуть.
"""

import os


def resource_for(text: str) -> str:
    """Какой ресурс просят в задаче (по тексту): камень → stone, иначе wood."""
    return "stone" if any(w in text.lower() for w in ("камен", "stone", "rock")) else "wood"


def route_dirs(cx: int, cy: int, tx: int, ty: int) -> list[str]:
    """Манхэттен-маршрут [cx,cy]→[tx,ty] как список move-направлений (x, потом y).

    Соответствие направлений — как на сервере: east = x+1, west = x-1,
    south = y+1, north = y-1. Тот же код, что в lesson-11-5/space/helpers.py."""
    dirs: list[str] = []
    dirs += ["east"] * (tx - cx) if tx > cx else ["west"] * (cx - tx)
    dirs += ["south"] * (ty - cy) if ty > cy else ["north"] * (cy - ty)
    return dirs


def facts_seed(character: dict, gmap: dict, text: str) -> str:
    """Нейтральные факты о живом мире — опора для слабой модели, БЕЗ маршрута.

    Мир персистентный, карта 7x7: позицию и карту всё равно берём инструментами
    (get_character + get_map), но житель мог остаться где угодно с прошлого
    раза — напоминаем модели, где она и что где лежит. Перечисляем ВСЕ виды
    сразу (деревья, камень, врагов), НЕ выбирая ресурс по тексту: выбор цели и
    порядок действий — дело скилла или самого агента. Раньше затравка называла
    только «нужный» ресурс — но с несколькими умениями это смещало выбор скилла
    (под разведку подсовывались клетки дерева, и модель тянула supply-run).
    Готового маршрута и плана затравка не даёт — их несёт skill (в этом урок
    13.6)."""
    cx, cy = character.get("x", 0), character.get("y", 0)
    by_kind: dict[str, list] = {}
    for tile in gmap.get("tiles", []):
        by_kind.setdefault(tile.get("content"), []).append((tile.get("x"), tile.get("y")))
    trees = by_kind.get("tree", [])
    rocks = by_kind.get("rock", [])
    enemies = by_kind.get("goblin", []) + by_kind.get("wolf", []) + by_kind.get("ogre", [])
    return (
        f"Ты сейчас стоишь на [{cx}, {cy}]. Дом (склад) на [0, 0]. "
        f"Деревья (wood) по клеткам: {[list(t) for t in trees] or 'нет'}. "
        f"Камень (stone) по клеткам: {[list(r) for r in rocks] or 'нет'}. "
        f"Клетки с врагами (не заходи): {[list(e) for e in enemies] or 'нет'}."
    )


def route_hint(character: dict, gmap: dict, text: str) -> str:
    """Подсказка «куда шагать» до ближайшего ресурса — ПОДПОРКА под слабую модель.

    Не факт о мире и не тело умения: детерминированный маршрут, посчитанный тем
    же route_dirs, что в 11.5. Порядок действий (дойти → gather → домой →
    проверить) остаётся за умением supply-run — здесь только навигация, потому
    что именно на ней небольшая локальная 7B срывается: без подсказки она путает
    координаты соседних клеток и рубит впустую (проверено на qwen-7B). Цель —
    БЛИЖАЙШИЙ ресурс под задачу (камень/stone → rock, иначе tree); ничью по
    дистанции ломаем по (x, y), чтобы демонстрируемый трейс был воспроизводим.
    Выключается WEAK_MODEL_ROUTE=0 — тогда навигацию ведёт реактивный цикл умения."""
    res = resource_for(text)
    kind = "rock" if res == "stone" else "tree"
    cx, cy = character.get("x", 0), character.get("y", 0)
    by_kind: dict[str, list] = {}
    for tile in gmap.get("tiles", []):
        by_kind.setdefault(tile.get("content"), []).append((tile.get("x"), tile.get("y")))
    targets = by_kind.get(kind, [])
    if not targets:
        return f"Подсказка: клеток {kind} ({res}) на карте сейчас нет — сообщи об этом, не блуждай."
    tx, ty = min(targets, key=lambda t: (abs(t[0] - cx) + abs(t[1] - cy), t[0], t[1]))
    to_res = ", ".join(f"move {d}" for d in route_dirs(cx, cy, tx, ty)) or "(ты уже на клетке ресурса)"
    # Дорога до цели — короткая (ближайший ресурс), её даём готовым списком. А вот
    # дорогу ДОМОЙ до [0, 0] НЕ считаем шагами: слабая 7B сбивается со счёта на
    # длинном маршруте (проверено — сворачивает на север раньше времени и застревает).
    # Угловой приём без счёта: move west, пока x не станет 0, потом move north, пока y
    # не станет 0. Считать не нужно — только сверять [x, y] после каждого move.
    return (
        f"Подсказка навигации (порядок действий бери из умения, это только «куда идти»): "
        f"ближайший {kind} на [{tx}, {ty}]. Дойти по одному шагу: {to_res}; встав РОВНО "
        f"на клетку — gather. Домой на [0, 0] БЕЗ СЧЁТА шагов: сначала move west, пока x "
        f"не станет 0, потом move north, пока y не станет 0 — просто сверяй [x, y] после "
        f"каждого move (дом сдаёт {res} сам). Если шаг ведёт на клетку врага — обойди."
    )


def fact_check(before: dict, after: dict, text: str) -> str:
    """Слова агента vs правда из игры: сдал ли он ресурс на склад НА САМОМ ДЕЛЕ.

    Считаем дельту склада (stored) до/после — так «в stored уже был wood с
    прошлого раза» не выдаётся за успех этого прогона. `banked` случается
    только на доме [0, 0]. Та же проверка, что в 11.5/14/14.5."""
    res = resource_for(text)
    x, y = after.get("x"), after.get("y")
    inv = after.get("inventory") or {}
    before_stored = (before.get("stored") or {}).get(res, 0)
    after_stored = (after.get("stored") or {}).get(res, 0)
    delta = after_stored - before_stored
    # Банк засчитываем и по словам «сдай/склад», и по возврату ДОМОЙ: в этой игре
    # депозита нет, дом [0, 0] сам разгружает рюкзак, поэтому «вернись домой» —
    # тоже требование сдать (тот же список триггеров, что в 14/14.5).
    need_bank = any(w in text.lower() for w in (
        "сда", "склад", "storehouse", "deposit", "банк", "дом", "home", "0, 0"))
    facts = (
        f"Проверка по факту (get_character): позиция [{x}, {y}], "
        f"рюкзак {dict(inv) or '{}'}, склад {dict(after.get('stored') or {}) or '{}'}."
    )
    if not need_bank:
        got = (inv.get(res, 0) or 0) + max(delta, 0)
        return ("✅ " + facts + f" {res} добыт." if got > 0
                else "ℹ️ " + facts + f" {res} пока не видно — проверьте прогон.")
    # Успех судим по одной дельте stored: сдача уже случилась, даже если агент
    # после банка успел отойти от дома (позиция и так напечатана в фактах).
    if delta > 0:
        return "✅ " + facts + f" Склад пополнился на {delta} {res} — сдано на самом деле."
    if inv.get(res, 0):
        return ("⚠️ " + facts + f" {res} ещё в РЮКЗАКЕ, житель не на доме [0, 0] — "
                "на склад НЕ сдан (агент поторопился с ответом). Попросите его "
                "вернуться на [0, 0] — дом сдаст сам.")
    return ("⚠️ " + facts + f" Склад по {res} не пополнился — задача не выполнена "
            "(агент мог не добыть ресурс или не дойти до дома).")
