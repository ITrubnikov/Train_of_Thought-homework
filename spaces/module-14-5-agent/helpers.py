"""Подпорки для СЛАБОЙ модели — вынесены из app.py специально, отдельным файлом.

Это НЕ про MCP (тема урока 14.5) и не про контракт tools — контракт живёт в
`cognopolis_mcp_server.py`, одинаков для любой модели и любого клиента. Здесь —
приёмы «как докрутить агента, когда мозг слабоват»: маленькая локальная 7B на
живой карте 7x7 сама теряется в навигации (пропускает get_map и уходит к краю)
и любит соврать «готово». Ровно те же подпорки стоят в шаблонах 11.5 и 13.6.

ВАЖНО про урок 14.5. Инструменты агент по-прежнему берёт ТОЛЬКО из каталога
MCP-сервера (tools/list) — в app.py их определений нет, и эти функции их не
добавляют. Затравку app.py собирает ВНЕШНЕЙ пробой живого API (обычный
requests, как уже существующий `_probe_character` для боковой панели), а НЕ
игровым инструментом. Проба — это разведка мира для человека и для затравки;
tools — это то, чем ходит сам агент. Граница урока цела.

Три подпорки:

1) `facts_seed` — затравка ФАКТОВ о живом мире: где житель стоит, что где лежит
   (деревья, камень, враги), где дом. Перечисляет все виды сразу — нейтрально.
2) `route_hint` — детерминированный маршрут «куда шагать» до ближайшего ресурса
   (тем же route_dirs, что в 11.5). В 13.6 порядок действий нёс skill, а hint
   давал только навигацию; здесь skill'а нет, поэтому hint доводит процедуру до
   конца: дойти → gather → домой (дом сдаёт сам). Выключается WEAK_MODEL_ROUTE=0.
3) `fact_check` — проверка результата состоянием, а не словами: дельта склада
   (stored) до/после прогона — сдал агент ресурс на самом деле или только заявил.

Мораль та же, что в 11.5/13.6: когда агент «тупит», сначала чинят контракт
(здесь он в MCP-сервере и он хороший); а эти подпорки — уже про слабость
КОНКРЕТНОЙ модели, и их честно держат отдельно. На сильной модели весь этот
файл можно выкинуть (WEAK_MODEL_ROUTE=0 и не подмешивать facts_seed).
"""

import os


def resource_for(text: str) -> str:
    """Какой ресурс просят в задаче (по тексту): камень → stone, иначе wood."""
    return "stone" if any(w in text.lower() for w in ("камен", "stone", "rock")) else "wood"


def route_dirs(cx: int, cy: int, tx: int, ty: int) -> list[str]:
    """Манхэттен-маршрут [cx,cy]→[tx,ty] как список move-направлений (x, потом y).

    Соответствие направлений — как на сервере: east = x+1, west = x-1,
    south = y+1, north = y-1. Тот же код, что в шаблонах 11.5 и 13.6."""
    dirs: list[str] = []
    dirs += ["east"] * (tx - cx) if tx > cx else ["west"] * (cx - tx)
    dirs += ["south"] * (ty - cy) if ty > cy else ["north"] * (cy - ty)
    return dirs


def facts_seed(character: dict, gmap: dict, text: str) -> str:
    """Нейтральные факты о живом мире — опора для слабой модели, БЕЗ маршрута.

    Мир персистентный, карта 7x7: житель мог остаться где угодно с прошлого
    раза, а маленькая локальная модель без напоминания пропускает get_map и
    уходит вслепую к краю (ровно как в разобранном падении 14.5). Позицию и
    карту всё равно можно взять инструментами — но затравкой мы кладём факты
    прямо в задачу, чтобы модель не блуждала. Перечисляем ВСЕ виды сразу
    (деревья, камень, враги), не выбирая ресурс по тексту, — выбор цели остаётся
    за агентом и маршрутной подсказкой."""
    cx, cy = character.get("x", 0), character.get("y", 0)
    by_kind: dict[str, list] = {}
    for tile in gmap.get("tiles", []):
        by_kind.setdefault(tile.get("content"), []).append((tile.get("x"), tile.get("y")))
    trees = by_kind.get("tree", [])
    rocks = by_kind.get("rock", [])
    enemies = by_kind.get("goblin", []) + by_kind.get("wolf", []) + by_kind.get("ogre", [])
    return (
        f"Ты сейчас стоишь на [{cx}, {cy}]. Дом (склад) на [0, 0]. "
        f"Деревья (wood) по клеткам: {[list(t) for t in trees] or 'нет'}. "
        f"Камень (stone) по клеткам: {[list(r) for r in rocks] or 'нет'}. "
        f"Клетки с врагами (не заходи): {[list(e) for e in enemies] or 'нет'}."
    )


def route_hint(character: dict, gmap: dict, text: str) -> str:
    """Готовый маршрут до ближайшего ресурса + возврат домой — ПОДПОРКА под слабую модель.

    Детерминированный путь, посчитанный тем же route_dirs, что в 11.5. В 13.6
    порядок действий нёс skill, поэтому hint давал только «куда шагать»; в 14.5
    скилла нет, и подсказка доводит процедуру до конца: дойти по одному шагу →
    gather → вернуться домой (дом сдаёт сам). Именно на навигации небольшая
    локальная 7B срывается — без подсказки путает координаты соседних клеток и
    рубит впустую (проверено на qwen-7B). Цель — БЛИЖАЙШИЙ ресурс под задачу
    (камень/stone → rock, иначе tree); ничью по дистанции ломаем по (x, y),
    чтобы трейс был воспроизводим. Выключается WEAK_MODEL_ROUTE=0 — тогда
    навигацию модель ведёт сама по фактам затравки и правилам мира."""
    res = resource_for(text)
    kind = "rock" if res == "stone" else "tree"
    cx, cy = character.get("x", 0), character.get("y", 0)
    by_kind: dict[str, list] = {}
    for tile in gmap.get("tiles", []):
        by_kind.setdefault(tile.get("content"), []).append((tile.get("x"), tile.get("y")))
    targets = by_kind.get(kind, [])
    if not targets:
        return f"Подсказка: клеток {kind} ({res}) на карте сейчас нет — сообщи об этом, не блуждай."
    tx, ty = min(targets, key=lambda t: (abs(t[0] - cx) + abs(t[1] - cy), t[0], t[1]))
    to_res = ", ".join(f"move {d}" for d in route_dirs(cx, cy, tx, ty)) or "(ты уже на клетке ресурса)"
    # Дорогу до цели даём готовым списком (маршрут короткий — ближайший ресурс).
    # А дорогу ДОМОЙ до [0, 0] НЕ считаем шагами: слабая 7B сбивается со счёта на
    # длинном пути (сворачивает раньше времени и застревает). Приём без счёта:
    # move west, пока x не станет 0, потом move north, пока y не станет 0 —
    # считать не нужно, только сверять [x, y] после каждого move.
    return (
        f"Рекомендуемый маршрут (иди по одному шагу, сверяя [x, y] в ответе move): "
        f"ближайший {kind} на [{tx}, {ty}]. Дойти: {to_res}; встав РОВНО на клетку — "
        f"gather(resource=\"{res}\"). Домой на [0, 0] БЕЗ СЧЁТА шагов: сначала move west, "
        f"пока x не станет 0, потом move north, пока y не станет 0 (дом сдаёт {res} сам). "
        f"Если шаг ведёт на клетку врага — обойди по другой оси."
    )


def fact_check(before: dict, after: dict, text: str) -> str:
    """Слова агента vs правда из игры: сдал ли он ресурс на склад НА САМОМ ДЕЛЕ.

    Считаем дельту склада (stored) до/после — так «в stored уже был wood с
    прошлого раза» не выдаётся за успех этого прогона. `banked` случается
    только на доме [0, 0]. Та же проверка, что в 11.5 и 13.6."""
    res = resource_for(text)
    x, y = after.get("x"), after.get("y")
    inv = after.get("inventory") or {}
    before_stored = (before.get("stored") or {}).get(res, 0)
    after_stored = (after.get("stored") or {}).get(res, 0)
    delta = after_stored - before_stored
    # Банк засчитываем и по словам «сдай/склад», и по возврату ДОМОЙ: в этой игре
    # депозита нет, дом [0, 0] сам разгружает рюкзак, поэтому «вернись домой на
    # (0, 0)» — тоже требование сдать (каноническая задача-плейсхолдер 14.5).
    # Отличие от 11.5/13.6, где «дом/home/0, 0» в этот список не входили: у них
    # задача уже несла слово «склад». Стоит перенести и туда, если правите разом.
    need_bank = any(w in text.lower() for w in (
        "сда", "склад", "storehouse", "deposit", "банк", "дом", "home", "0, 0"))
    facts = (
        f"Проверка по факту (get_character): позиция [{x}, {y}], "
        f"рюкзак {dict(inv) or '{}'}, склад {dict(after.get('stored') or {}) or '{}'}."
    )
    if not need_bank:
        got = (inv.get(res, 0) or 0) + max(delta, 0)
        return ("✅ " + facts + f" {res} добыт." if got > 0
                else "ℹ️ " + facts + f" {res} пока не видно — проверьте прогон.")
    if delta > 0 and [x, y] == [0, 0]:
        return "✅ " + facts + f" Склад пополнился на {delta} {res} — сдано на самом деле."
    if inv.get(res, 0):
        return ("⚠️ " + facts + f" {res} ещё в РЮКЗАКЕ, житель не на доме [0, 0] — "
                "на склад НЕ сдан (агент поторопился с ответом). Попросите его "
                "вернуться на [0, 0] — дом сдаст сам.")
    return ("⚠️ " + facts + f" Склад по {res} не пополнился — задача не выполнена "
            "(агент мог не добыть ресурс или не дойти до дома).")
