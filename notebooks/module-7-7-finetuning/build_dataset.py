# Контрольные посторонние вопросы (НЕ про Кьюби, НЕ в train).
# Нужны, чтобы показать: после файнтюна модель не «сломалась» на обычных задачах.
CONTROL_EVAL = [
    {"q": "Сколько будет 2+2?", "note": "ожидаем 4 — модель не должна деградировать"},
    {"q": "Назови столицу Франции.", "note": "ожидаем Париж"},
    {"q": "Напиши очень короткое хокку про осень.", "note": "ожидаем связный текст, не про Кьюби"},
]


def msg(q, a):
    return {"messages": [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": q},
        {"role": "assistant", "content": a},
    ]}


def build():
    train, eval_rows = [], []

    for fact in FACTS:
        for q in fact["train"]:
            train.append(msg(q, fact["answer"]))
        for q in fact["eval"]:
            row = msg(q, fact["answer"])
            row["type"] = "fact_paraphrase"
            eval_rows.append(row)

    for c in COMBOS_TRAIN:
        train.append(msg(c["q"], c["a"]))
    for c in COMBOS_EVAL:
        row = msg(c["q"], c["a"])
        row["type"] = "combo"
        eval_rows.append(row)

    # Контроль: кладём только system+user (без «правильного» ответа про Кьюби),
    # ответ модели на это смотрим глазами в ноутбуке.
    for c in CONTROL_EVAL:
        eval_rows.append({
            "messages": [
                {"role": "system", "content": SYSTEM},
                {"role": "user", "content": c["q"]},
            ],
            "type": "control",
            "note": c["note"],
        })

    return train, eval_rows


def dump(rows, path):
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(here, "data")
    os.makedirs(data_dir, exist_ok=True)

    train, eval_rows = build()
    dump(train, os.path.join(data_dir, "qubi_train.jsonl"))
    dump(eval_rows, os.path.join(data_dir, "qubi_eval.jsonl"))

    n_ctrl = sum(1 for r in eval_rows if r.get("type") == "control")
    print(f"train: {len(train)} примеров -> data/qubi_train.jsonl")
