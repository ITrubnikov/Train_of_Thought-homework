# Контрольные посторонние вопросы (НЕ про Кьюби, НЕ из REHEARSAL).
# Показывают: после файнтюна модель не «сломалась» на обычных задачах.
CONTROL_EVAL = [
    {"q": "Сколько будет 2+2?", "note": "ждём 4"},
    {"q": "Сколько будет 12 минус 5?", "note": "ждём 7"},
    {"q": "Сколько будет 5 умножить на 6?", "note": "ждём 30"},
    {"q": "Переведи слово «dog» на русский.", "note": "ждём «собака»"},
    {"q": "Напиши очень короткое хокку про осень.", "note": "ждём связный текст не про Кьюби"},
]


def msg(q, a):
    return {"messages": [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": q},
        {"role": "assistant", "content": a},
    ]}


def build():
    train, held = [], []

    for fact in FACTS:
        for q in fact["train"]:
            train.append(msg(q, fact["answer"]))
        for q in fact["eval"]:
            row = msg(q, fact["answer"]); row["type"] = "fact_paraphrase"
            held.append(row)

    for c in COMBOS_TRAIN:
        train.append(msg(c["q"], c["a"]))

    for q, a in REHEARSAL:
        row = msg(q, a); row["type"] = "rehearsal"
        train.append(row)

    # Контроль: только system+user, ответ модели смотрим глазами в ноутбуке.
    for c in CONTROL_EVAL:
        held.append({
            "messages": [
                {"role": "system", "content": SYSTEM},
                {"role": "user", "content": c["q"]},
            ],
            "type": "control", "note": c["note"],
        })

    return train, held


def dump(rows, path):
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(here, "data")
    os.makedirs(data_dir, exist_ok=True)

    train, held = build()
    dump(train, os.path.join(data_dir, "qubi_train.jsonl"))
    dump(held, os.path.join(data_dir, "qubi_eval.jsonl"))

    n_know = sum(1 for r in train if r.get("type") != "rehearsal")
    n_reh = sum(1 for r in train if r.get("type") == "rehearsal")
    n_ctrl = sum(1 for r in held if r.get("type") == "control")
    print(f"train: {len(train)} ({n_know} про Кьюби + {n_reh} rehearsal) -> data/qubi_train.jsonl")
    print(f"held:  {len(held)} ({len(held)-n_ctrl} перефразировок + {n_ctrl} контрольных) -> data/qubi_eval.jsonl")
